/**
 * Событие на `window`, которым стор сообщает о своём появлении.
 *
 * Часть публичного контракта. Нужно оно вот зачем: по конфигу сборки нельзя понять, грузит ли
 * приложение модули — хосту-потребителю ключ `modules` не нужен, он подключает их в рантайме.
 * Поэтому панель показывает бейдж не сразу, а по этому событию: пока ни одной попытки загрузить
 * модуль не было, показывать в панели нечего и бейдж в углу только мешает.
 *
 * Событие разовое: стор создаётся один раз на страницу.
 */
export const DEVTOOLS_READY_EVENT = 'arui:devtools:ready';

/**
 * Сообщает странице, что стор появился.
 *
 * Лучшее усилие и ничего больше: слушателей может не быть вовсе, а если событие не доедет,
 * панель узнает о сторе своим опросом — просто позже. Поэтому любые ошибки тут гасятся,
 * ронять из-за них загрузку модуля нельзя.
 */
export function announceStoreCreated() {
    try {
        if (typeof window === 'undefined' || typeof CustomEvent !== 'function') {
            return;
        }

        window.dispatchEvent(new CustomEvent(DEVTOOLS_READY_EVENT));
    } catch {
        // событие — не обязательство, живём дальше
    }
}
